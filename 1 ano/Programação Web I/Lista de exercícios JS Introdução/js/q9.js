dia = parseInt(prompt("Digite um numero de 1 a 7:"));

switch (dia) {
    case 1:
        alert("Domingo");
        break;
    case 2:
        alert("Segunda-feira");
        break;
    case 3:
        alert("Terca-feira");
        break;
    case 4:
        alert("Quarta-feira");
        break;
    case 5:
        alert("Quinta-feira");
        break;
    case 6:
        alert("Sexta-feira");
        break;
    case 7:
        alert("Sabado");
        break;
    default:
        alert("Numero invalido");
}
